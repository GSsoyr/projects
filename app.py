import streamlit as st
import easyocr
import numpy as np
from PIL import Image
import re

# Настройка на заглавието на страницата
st.set_page_config(page_title="ИИ Химия на храните", page_icon="🧪")

# База данни с вредни съставки (базирана на твоята презентация)
HARMFUL_INGREDIENTS = {
    "E407": "Карагенан - Може да предизвика възпаления в червата и храносмилателни проблеми.",
    "E621": "Мононатриев глутамат - Подсилвател на вкуса. Може да причини главоболие и алергии.",
    "E250": "Натриев нитрит - Консервант в колбасите. Свързва се с риск от онкологични заболявания.",
    "E450": "Дифосфати - Нарушават калциево-фосфорния баланс и вредят на костите и бъбреците.",
    "E262": "Натриев ацетат - Може да раздразни стомаха при по-големи количества.",
    "E300": "Аскорбинова киселина - Витамин С, но в големи дози може да дразни стомаха.",
    "E330": "Лимонена киселина - В големи количества уврежда зъбния емайл.",
    "E952": "Цикламат - Изкуствен подсладител, забранен в някои страни поради риск за здравето.",
    "E471": "Емулгатор (Моно- и диглицериди) - Обикновено безопасен, но често е индикация за преработена храна.",
    "E102": "Тартразин (Оцветител) - Може да причини хиперактивност при децата.",
    "E129": "Алура червено (Оцветител) - Потенциален алерген.",
}

# Функция за зареждане на EasyOCR (кеширана, за да не се зарежда при всяко кликване)
@st.cache_resource
def load_reader():
    # Зареждаме български и английски език
    return easyocr.Reader(['bg', 'en'])

reader = load_reader()

# --- ИНТЕРФЕЙС ---
st.title("🧪 ИИ Анализатор на хранителни етикети")
st.write("Качете снимка на етикета на продукта и изкуственият интелект ще открие вредните съставки.")

# Избор на метод за качване
source = st.radio("Изберете източник:", ("Качване на файл", "Използване на камера"))

if source == "Качване на файл":
    uploaded_file = st.file_uploader("Изберете изображение...", type=["jpg", "jpeg", "png"])
else:
    uploaded_file = st.camera_input("Снимайте етикета")

if uploaded_file is not None:
    # Показване на изображението
    image = Image.open(uploaded_file)
    st.image(image, caption='Качено изображение', use_container_width=True)
    
    with st.spinner('ИИ анализира текста... моля изчакайте.'):
        # Превръщане в numpy array за EasyOCR
        img_array = np.array(image)
        
        # Разпознаване на текст
        results = reader.readtext(img_array, detail=0)
        full_text = " ".join(results).upper()
        
        st.subheader("📝 Разпознат текст:")
        st.write(full_text)
        
        # Търсене на вредни Е-номера чрез Regex и сравнение
        found_harmful = []
        
        # Търсим съвпадения от нашата база данни
        for code, description in HARMFUL_INGREDIENTS.items():
            # Използваме редовен израз, за да намерим кода (напр. Е621 или Е 621)
            pattern = rf"{code[0]}\s?{code[1:]}"
            if re.search(pattern, full_text):
                found_harmful.append((code, description))
        
        # --- РЕЗУЛТАТИ ---
        st.divider()
        if found_harmful:
            st.warning(f"⚠️ Открити са {len(found_harmful)} потенциално вредни съставки!")
            for code, desc in found_harmful:
                with st.expander(f"🔴 {code}"):
                    st.write(desc)
            
            st.subheader("💡 Здравословна алтернатива:")
            st.info("Опитайте се да замените този продукт с пресни плодове, зеленчуци или домашно приготвена храна без консерванти.")
        else:
            st.success("✅ Не бяха открити опасни Е-номера от нашия списък.")
            st.write("Винаги проверявайте съдържанието на захар и сол!")

# Футър
st.sidebar.markdown("---")
st.sidebar.write("📌 **Проект:** Химия на храните и ИИ")
st.sidebar.write("🚀 **Технология:** EasyOCR & Streamlit")
